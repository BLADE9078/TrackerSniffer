// Evaluates domain extraction, tracker classification (false positives) and lookup performance
// on the labeled test set, and writes docs/evaluation-results.md (+ .json).
// Usage: npm run evaluate
import { readFile, writeFile } from 'node:fs/promises';
import { hostnameFromUrl } from '../src/lib/domain.js';
import { createTrackerIndex, matchTracker } from '../src/lib/trackers.js';
import { buildAudit } from '../src/lib/audit.js';

const catalog = JSON.parse(await readFile(new URL('../data/trackers.json', import.meta.url), 'utf8'));
const labeled = JSON.parse(await readFile(new URL('../tests/fixtures/labeled-domains.json', import.meta.url), 'utf8'));
const index = createTrackerIndex(catalog);

const TARGETS = {
  spec_accuracy: 100,          // % of labeled cases where match + category equal the specification
  lookalike_false_positives: 0, // lookalike hostnames wrongly matched
  lookup_10k_ms: 100,           // 10,000 lookups
  audit_300_hosts_ms: 20,       // building one audit with 300 observed hostnames (median)
};

// 1. Specification accuracy, per kind
const byKind = {};
let specCorrect = 0;
const failures = [];
for (const row of labeled) {
  const { hostname } = hostnameFromUrl(row.url);
  const m = matchTracker(hostname, index);
  const ok = m.matched === row.expected_match && m.category === row.expected_category && (row.kind !== 'malformed' || hostname === null);
  byKind[row.kind] ??= { total: 0, correct: 0 };
  byKind[row.kind].total++;
  if (ok) { byKind[row.kind].correct++; specCorrect++; } else failures.push(row.url);
  row._matched = m.matched;
}
const specAccuracy = Math.round((specCorrect / labeled.length) * 1000) / 10;
const lookalikeFP = labeled.filter((r) => r.kind === 'lookalike' && r._matched).length;

// 2. Real-world labels (independent of the list): precision / recall of "recognized tracker"
const valid = labeled.filter((r) => r.truth !== 'invalid');
const tp = valid.filter((r) => r.truth === 'tracker' && r._matched).length;
const fn = valid.filter((r) => r.truth === 'tracker' && !r._matched);
const fp = valid.filter((r) => r.truth === 'not-tracker' && r._matched);
const tn = valid.filter((r) => r.truth === 'not-tracker' && !r._matched).length;
const precision = Math.round((tp / (tp + fp.length)) * 1000) / 10;
const recall = Math.round((tp / (tp + fn.length)) * 1000) / 10;
const fpExcludingContent = fp.filter((r) => r.kind !== 'listed-content').length;

// 3. Performance
const hosts = [];
for (let i = 0; i < 5000; i++) hosts.push(`a${i}.securepubads.g.doubleclick.net`, `cdn${i}.unknown-site-${i}.co.in`);
const runs = [];
for (let k = 0; k < 7; k++) {
  const t0 = performance.now();
  for (const h of hosts) matchTracker(h, index);
  runs.push(performance.now() - t0);
}
runs.sort((a, b) => a - b);
const lookupMs = Math.round(runs[3] * 100) / 100;

const observedHosts = {};
const trackerKeys = Object.keys(catalog.trackers);
for (let i = 0; i < 150; i++) observedHosts[`x${i}.${trackerKeys[(i * 29) % trackerKeys.length]}`] = { count: 1, firstSeenMs: i };
for (let i = 0; i < 145; i++) observedHosts[`cdn.site${i}.com`] = { count: 1, firstSeenMs: i };
for (let i = 0; i < 5; i++) observedHosts[`s${i}.news.in`] = { count: 1, firstSeenMs: i };
const auditRuns = [];
for (let k = 0; k < 51; k++) {
  const t0 = performance.now();
  buildAudit({ pageUrl: 'https://www.news.in/', observation: { pageUrl: 'https://www.news.in/', startedAt: Date.now() - 10000, hosts: observedHosts }, index });
  auditRuns.push(performance.now() - t0);
}
auditRuns.sort((a, b) => a - b);
const auditMs = Math.round(auditRuns[25] * 100) / 100;

const results = {
  generated_at: new Date().toISOString(),
  node: process.version,
  tracker_list: catalog.meta.version,
  tracker_list_domains: index.size,
  labeled_cases: labeled.length,
  spec_accuracy_pct: specAccuracy,
  by_kind: byKind,
  failures,
  lookalike_false_positives: lookalikeFP,
  real_world: { tp, fp: fp.length, fn: fn.length, tn, precision_pct: precision, recall_pct: recall, fp_excluding_listed_content: fpExcludingContent, false_negatives: fn.map((r) => r.url), false_positives: fp.map((r) => r.url) },
  performance: { lookups: hosts.length, lookup_median_ms: lookupMs, per_lookup_us: Math.round((lookupMs / hosts.length) * 1e5) / 100, audit_300_hosts_median_ms: auditMs },
  targets: TARGETS,
};
results.targets_met = {
  spec_accuracy: specAccuracy >= TARGETS.spec_accuracy,
  lookalike_false_positives: lookalikeFP <= TARGETS.lookalike_false_positives,
  lookup_10k_ms: lookupMs < TARGETS.lookup_10k_ms,
  audit_300_hosts_ms: auditMs < TARGETS.audit_300_hosts_ms,
};

const yes = (b) => (b ? 'Met' : '**Not met**');
const md = `# Evaluation results

Generated by \`npm run evaluate\` on ${results.generated_at.slice(0, 10)} (Node ${process.version}), tracker list \`${results.tracker_list}\` (${results.tracker_list_domains} domains), labeled set \`tests/fixtures/labeled-domains.json\` (${labeled.length} cases).

## Targets

| Target | Threshold | Result | Status |
|---|---|---|---|
| Matching and extraction follow the specification | ${TARGETS.spec_accuracy}% of labeled cases | ${specAccuracy}% | ${yes(results.targets_met.spec_accuracy)} |
| False positives on lookalike domains | ${TARGETS.lookalike_false_positives} | ${lookalikeFP} of ${byKind.lookalike.total} | ${yes(results.targets_met.lookalike_false_positives)} |
| Lookup speed | 10,000 lookups in under ${TARGETS.lookup_10k_ms} ms | ${lookupMs} ms (${results.performance.per_lookup_us} µs each) | ${yes(results.targets_met.lookup_10k_ms)} |
| Audit build time | 300 observed hostnames in under ${TARGETS.audit_300_hosts_ms} ms | ${auditMs} ms (median of 51) | ${yes(results.targets_met.audit_300_hosts_ms)} |

## Results by case type

| Case type | Correct / total |
|---|---|
${Object.entries(byKind).map(([k, v]) => `| ${k} | ${v.correct} / ${v.total} |`).join('\n')}

## Against independent real-world labels

The labeled set also records whether each domain is a tracker in practice (judged independently of the list). This measures the **tracker list's coverage**, not the matcher:

| | Labeled tracker | Labeled not a tracker |
|---|---|---|
| Recognized by TrackerSniffer | ${tp} (true positives) | ${fp.length} (false positives) |
| Not recognized | ${fn.length} (false negatives) | ${tn} (true negatives) |

- Precision ${precision}%, recall ${recall}%.
- All ${fp.length} false positives are CDNs/embeds that Disconnect lists under **Content** (${fp.map((r) => hostnameFromUrl(r.url).hostname).join(', ')}). Excluding that category, false positives: **${fpExcludingContent}**. They are shown as "Embedded content" and charged only 1 point each.
- False negatives (${fn.map((r) => hostnameFromUrl(r.url).hostname).join(', ')}) are real trackers absent from this list version. They appear under "Unknown", never as "safe".
`;
await writeFile(new URL('../docs/evaluation-results.md', import.meta.url), md);
await writeFile(new URL('../docs/evaluation-results.json', import.meta.url), JSON.stringify(results, null, 2) + '\n');
console.log(md);
if (Object.values(results.targets_met).includes(false)) process.exit(1);
